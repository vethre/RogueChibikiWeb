const languageMap = {
  en: "en-US",
  uk: "uk",
  ru: "ru"
};

const i18nNodes = document.querySelectorAll("[data-i18n]");
const altNodes = document.querySelectorAll("[data-i18n-alt]");
const languageButtons = document.querySelectorAll("[data-lang]");
const releaseContainer = document.querySelector("#release-notes");
const musicButton = document.querySelector("#music-toggle");
const musicAudio = document.querySelector("#bg-music");
const volumeSlider = document.querySelector("#music-volume");

function renderReleaseNotes(lang) {
  if (!releaseContainer) return;

  const notes = releaseNotes[lang] || releaseNotes.en;
  releaseContainer.innerHTML = "";

  notes.forEach((note) => {
    const card = document.createElement("article");
    card.className = "release-card";

    const version = document.createElement("div");
    version.className = "release-version";
    version.textContent = `v${note.version}`;

    const date = document.createElement("div");
    date.className = "release-date";
    date.textContent = note.date;

    const list = document.createElement("ul");
    note.highlights.forEach((item) => {
      const li = document.createElement("li");
      li.textContent = item;
      list.appendChild(li);
    });

    card.appendChild(version);
    card.appendChild(date);
    card.appendChild(list);
    releaseContainer.appendChild(card);
  });
}

function updateMusicLabel(lang) {
  if (!musicButton || !musicAudio) {
    return;
  }
  if (translations[lang] && translations[lang].music_play) {
    const isPaused = musicAudio.paused;
    musicButton.textContent = isPaused ? translations[lang].music_play : translations[lang].music_pause;
  }
}

function setLanguage(lang) {
  const dict = translations[lang] || translations.en;

  i18nNodes.forEach((node) => {
    const key = node.dataset.i18n;
    if (dict[key]) {
      node.textContent = dict[key];
    }
  });

  altNodes.forEach((node) => {
    const key = node.dataset.i18nAlt;
    if (dict[key]) {
      node.setAttribute("alt", dict[key]);
    }
  });

  document.documentElement.lang = languageMap[lang] || "en-US";
  languageButtons.forEach((button) => {
    button.classList.toggle("is-active", button.dataset.lang === lang);
  });

  renderReleaseNotes(lang);
  updateMusicLabel(lang);
  localStorage.setItem("rc-lang", lang);
}

function initMusic() {
  if (!musicAudio || !musicButton || !volumeSlider) return;

  musicAudio.volume = Number(volumeSlider.value);

  volumeSlider.addEventListener("input", (event) => {
    musicAudio.volume = Number(event.target.value);
  });

  musicButton.addEventListener("click", async () => {
    if (musicAudio.paused) {
      try {
        await musicAudio.play();
      } catch (error) {
        console.warn("Music playback blocked until user interaction.");
      }
    } else {
      musicAudio.pause();
    }
    updateMusicLabel(getCurrentLanguage());
  });
}

function getCurrentLanguage() {
  const active = document.querySelector("[data-lang].is-active");
  return active ? active.dataset.lang : "en";
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

const savedLang = localStorage.getItem("rc-lang") || "en";
setLanguage(savedLang);
initMusic();

const observer = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      }
    });
  },
  { threshold: 0.2 }
);

const revealNodes = document.querySelectorAll(".reveal");
revealNodes.forEach((node) => observer.observe(node));
